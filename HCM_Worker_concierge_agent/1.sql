/* FORMULA NAME: HOUSING ALLOWANCE
* DESCRIPTION  : THIS FORMULA CALCULATES THE HOUSING ALLOWANCE FOR TAMAM EMPLOYEES
* FORMULA TYPE : ORACLE PAYROLL                               
 
VERSION   AUTHOR          DATE        DESCRIPTION
-------  ---------------  ----------- ---------------------------
--------------------------------------------------------------------------------*/
 
/**********************************ALIAS SECTION***********************************/
 
ALIAS HOUSING_ALLOWANCE_REL_ITD 								AS HOUSING_ITD
ALIAS PAY_EARN_PERIOD_END                                   	AS PERIOD_ED
ALIAS PER_PER_TERMINATION_DATE                              	AS TERM_DATE
 
 
DEFAULT FOR L_EFF_DATE                                      					IS '0001/01/01 00:00:00' (DATE)
DEFAULT FOR PAY_EARN_PERIOD_END                             					IS '4712/12/31 00:00:00' (DATE) 
DEFAULT FOR PAY_EARN_PERIOD_START 												IS '4712/12/31 00:00:00' (DATE)
DEFAULT FOR PAY_ASG_TERMINATION_DATE 											IS '4712/12/31 00:00:00' (DATE)
DEFAULT FOR PER_PER_TERMINATION_DATE                        					IS '4712/12/31 00:00:00' (DATE) 
DEFAULT FOR PAY_ASG_HIRE_DATE 													IS '4712/12/31 00:00:00' (DATE)
DEFAULT FOR PRORATE_START 														IS '0001/01/01 00:00:00' (DATE)
DEFAULT FOR PRORATE_END 														IS '0001/01/01 00:00:00' (DATE)
DEFAULT FOR HOUSING_ALLOWANCE_RETRO_AMOUNT_ASG_ENTRY_VALUE 						IS 0
DEFAULT FOR HOUSING_ALLOWANCE_RETROACTIVE_REL_ITD	 							IS 0
DEFAULT FOR HOUSING_ALLOWANCE_REL_ITD 											IS 0
DEFAULT_DATA_VALUE FOR EMPLOYEE_GOSI_DETAILS_DIR_CARD_DIR_CARD_ID  				IS -1
 
 
INPUTS ARE        AMOUNT (NUMBER),
                  PERIODICITY (TEXT),
                  REDUCE_REGULAR (TEXT),
                  PAY_VALUE(NUMBER),
                  NEW_GUESS(NUMBER),
                  ADDITIONAL_AMOUNT(NUMBER),  
                  GUESS(NUMBER),   
                  FIRST_RUN(NUMBER),
                  NET(NUMBER),
                  PRORATION_METHOD(TEXT),
				  WORK_UNITS_CONVERSION_RULE(TEXT),
                  PRORATION_CONVERSION_RULE(TEXT),
                  PERIODICITY_CONVERSION_RULE(TEXT),
                  REPORTING_UNIT(TEXT),
                  PRORATE_START (DATE),
                  PRORATE_END	(DATE)
 
 
/**********************************VARIABLE SECTION***********************************/		
L_ASSIGNMENT_ID	= ASG_HR_ASG_ID
L_TRM_ID		= TERM_HR_TERM_ID
L_HR_REL_ID		= GET_CONTEXT(PAYROLL_RELATIONSHIP_ID, 0)
P_PERSON_ID		= GET_CONTEXT(PERSON_ID, 0)
L_EFF_DATE		= LEAST(PERIOD_ED,TERM_DATE)
L_HIRE_DATE		= TRUNC(PAY_ASG_HIRE_DATE)
L_TERM_DATE		= TRUNC(PAY_ASG_TERMINATION_DATE)
L_PERIOD_SDATE	= TRUNC(PAY_EARN_PERIOD_START)
L_PERIOD_EDATE	= TRUNC(PAY_EARN_PERIOD_END)
L_CALC_SDATE	= GREATEST(L_HIRE_DATE, L_PERIOD_SDATE,PRORATE_START)
L_CALC_EDATE	= LEAST(L_TERM_DATE, L_PERIOD_EDATE,PRORATE_END)
L_CALENDAR_DAYS	= DAYS_BETWEEN(L_PERIOD_EDATE, L_PERIOD_SDATE) + 1
PAY_VALUE = 0
MSG = ' '
 
 
CALC_BREAKDOWN_ID_1 = EMPLOYEE_GOSI_DETAILS_DIR_CARD_DIR_CARD_ID[1]
 
CHANGE_CONTEXTS(CALC_BREAKDOWN_ID = CALC_BREAKDOWN_ID_1)
(
	L_HOUSING_ITD		= HOUSING_ITD
	L_HOUSING_PAID		= HOUSING_ALLOWANCE_REL_ITD
	L_HOUSING_RETRO		= HOUSING_ALLOWANCE_RETROACTIVE_REL_ITD
)
 
/************GET GRADE ALLOWANCE*************/
L_MODE			= 'PER_ASG_GRADE_NAME'
CALL_FORMULA('GET_HR_DATA_1'	,
    L_ASSIGNMENT_ID > 'HR_ID'		,
    L_EFF_DATE 		> 'EFF_DATE'	,
    L_MODE    		> 'MODE'		,
    X_OUTPUT_TEXT   < 'X_OUTPUT_TEXT'  DEFAULT 'XX'
)
 
GRADE = X_OUTPUT_TEXT
 
 
/* FETCH AMOUNT FROM USER DEFINED TABLE */
PAY_VALUE = TO_NUMBER(GET_TABLE_VALUE('TAMAM_HOUSING_ALL_NEW', 'GRADE', GRADE, '0'))
 
 
/*4000/SAR PACKAGE OF BASIC SALARY AND NO TRANSPORTATION ALLOWANCE AND HOUSING ALLOWANCE AS PER MUTUAL CONTRACT FROM BOTH PARTIES - ISSUED RAISED BY NAIF.TAMAM - EFFECTIVE FROM JUL-2025 - 4746*/
/* IF(P_PERSON_ID = 300000003192332) THEN
(
	PAY_VALUE = 0
) */
 
/*LATE HIRE CASES RETRO CUSTOM TRIGGER*/
IF L_HIRE_DATE < L_PERIOD_SDATE AND LAST_DAY(L_HIRE_DATE) = ADD_DAYS(L_PERIOD_SDATE, - 1) AND (L_HOUSING_PAID = 0 AND L_HOUSING_RETRO = 0 AND HOUSING_ALLOWANCE_RETRO_AMOUNT_ASG_ENTRY_VALUE = 0 )  THEN 
/*AND TO_CHAR(L_PERIOD_SDATE,'MM-YYYY') <> '05-2025'  EXCLUDING LIVE MONTH */  
(
	L_END_DATE		= LAST_DAY(L_HIRE_DATE)
	L_START_DATE	= L_HIRE_DATE
	L_PRORATE_DAYS	= DAYS_BETWEEN(L_END_DATE, L_START_DATE) + 1
	L_CALENDAR_DAYS = TO_NUMBER(TO_CHAR(L_END_DATE,'DD'))
	 IF L_START_DATE <> TRUNC (L_PERIOD_SDATE, 'MONTH') THEN 
	 (
	    L_HOUSING_RETRO		= ROUND((PAY_VALUE / L_CALENDAR_DAYS) * L_PRORATE_DAYS,2) 
	  )
	  /* ELSE
	  (
	    L_HOUSING_RETRO		= PAY_VALUE
      ) */
	  RETURN PAY_VALUE, GRADE, L_HOUSING_RETRO, MSG
)
 
ELSE (
 
		PAY_VALUE  =  PAY_VALUE
 
)
RETURN PAY_VALUE, GRADE